//! Compile the same contract module as EnvKey/EnvValue/EnvMap, without Cargo.

#[path = "../crates/libs/guest-process/src/env/contract.rs"]
mod contract;

use contract::*;

fn go_bytes(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("\\x{byte:02x}")).collect()
}

fn main() {
    println!(
        r#"// Code generated by scripts/generate-env-contract.sh; DO NOT EDIT.

package main

import "strings"

const envMaxEntries = {MAX_ENV_ENTRIES}
const envMaxKeyBytes = {MAX_ENV_KEY_BYTES}
const envMaxValueBytes = {MAX_ENV_VALUE_BYTES}
const envMaxTotalBytes = {MAX_ENV_TOTAL_BYTES}
const envKeyFirst = "{}"
const envKeyRest = "{}"

func validEnvKeyGrammar(key string) bool {{
	if len(key) == 0 || strings.IndexByte(envKeyFirst, key[0]) < 0 {{
		return false
	}}
	for i := 1; i < len(key); i++ {{
		if strings.IndexByte(envKeyRest, key[i]) < 0 {{
			return false
		}}
	}}
	return true
}}"#,
        go_bytes(ENV_KEY_FIRST),
        go_bytes(ENV_KEY_REST),
    );
}
