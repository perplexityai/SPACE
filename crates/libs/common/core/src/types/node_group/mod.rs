//! Node groups and the template ↔ node-group compatibility relation.
//!
//! A node group is a named pool of worker nodes. A **generic** group
//! (`org_id` absent) is shared capacity: it hosts only generic templates, from
//! any org. An **org-specific** group (`org_id` present) is dedicated hardware
//! for one org: it serves only that org's sandboxes, and only templates its
//! [`NodeGroupTemplatePolicy`] admits.
//!
//! [`NodeGroup::compatible`] is the single predicate deciding which groups a
//! sandbox may land in. It yields two symmetric isolation guarantees:
//!
//! 1. **Data isolation** — an org-specific template only ever runs on its
//!    owning org's dedicated nodes.
//! 2. **Capacity isolation** — a dedicated node group only ever runs its
//!    owning org's sandboxes.
//!
//! Users never name a node group; placement derives the compatible set from
//! the template they asked for and the org they belong to.

