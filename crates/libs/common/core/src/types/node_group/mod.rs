/// Maximum byte length of a [`NodeGroupName`].
///
/// Node group names are used verbatim as Kubernetes node label values, which
/// RFC 1123 caps at 63 characters.
pub const NODE_GROUP_NAME_MAX_LEN: usize = 63;

/// Stable database identity for a node group.
///
/// App-owned UUIDv7 values, generated by the inserting code rather than a
/// database default.
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
#[cfg_attr(feature = "serde", serde(try_from = "String", into = "String"))]
#[derive(Debug, Clone, Copy, Eq, PartialEq, Ord, PartialOrd, Hash)]
pub struct NodeGroupId(Uuid);

impl NodeGroupId {
    /// Creates a fresh UUIDv7-backed node group ID.
    pub fn new() -> Self {
        Self(Uuid::now_v7())
    }

    /// Wraps an already parsed UUID as a node group ID.
    pub const fn from_uuid(uuid: Uuid) -> Self {
        Self(uuid)
    }

    /// Returns the underlying UUID.
    pub const fn as_uuid(self) -> Uuid {
        self.0
    }
}

impl Default for NodeGroupId {
    fn default() -> Self {
        Self::new()
    }
}

impl fmt::Display for NodeGroupId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.0.fmt(f)
    }
}

impl FromStr for NodeGroupId {
    type Err = uuid::Error;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        value.parse::<Uuid>().map(Self)
    }
}

impl From<NodeGroupId> for Uuid {
    fn from(value: NodeGroupId) -> Self {
        value.0
    }
}

impl From<NodeGroupId> for String {
    fn from(value: NodeGroupId) -> Self {
        value.to_string()
    }
}

impl TryFrom<String> for NodeGroupId {
    type Error = uuid::Error;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        value.parse()
    }
}

/// Error returned by the node group name parser.
///
/// # Examples
///
/// ```rust
/// # use pplx_space_common_core::types::NodeGroupName;
/// assert!(NodeGroupName::parse("Not-A-Label").is_err());
/// ```
#[derive(Debug, Clone, Eq, PartialEq, thiserror::Error)]
pub enum NodeGroupNameParseError {
    #[error("node group name must not be empty")]
    Empty,
    #[error("node group name must be at most {max} bytes, got {actual}")]
    TooLong { max: usize, actual: usize },
    #[error("node group name must contain only lowercase ASCII alphanumeric characters or '-'")]
    InvalidCharacter,
    #[error("node group name must start and end with a lowercase ASCII alphanumeric character")]
    InvalidBoundary,
}

/// Validated node group name: a lowercase RFC 1123 label slug.
///
/// The name is used verbatim as the value of the node-group node label on
/// Kubernetes, so it is parsed once at the wire boundary — an invalid name
/// must never reach a node label or affinity term and make pods
/// unschedulable. The accepted grammar (lowercase ASCII alphanumerics and
/// `-`, alphanumeric at both ends, at most 63 bytes) matches the `name` CHECK
/// on the `node_groups` table; keep the two in sync.
///
/// # Examples
///
/// ```rust
/// # use pplx_space_common_core::types::NodeGroupName;
/// let name = NodeGroupName::parse("org-acme-1").unwrap();
/// assert_eq!(name.as_str(), "org-acme-1");
/// ```
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
#[cfg_attr(feature = "serde", serde(try_from = "String", into = "String"))]
#[derive(Clone, Debug, Eq, PartialEq, Ord, PartialOrd, Hash)]
pub struct NodeGroupName(String);

impl NodeGroupName {
    /// Parses a non-empty, label-safe node group name.
    ///
    /// # Examples
    ///
    /// ```rust
    /// # use pplx_space_common_core::types::NodeGroupName;
    /// assert!(NodeGroupName::parse("workers").is_ok());
    /// assert!(NodeGroupName::parse("-workers").is_err());
    /// ```
    pub fn parse(value: impl Into<String>) -> Result<Self, NodeGroupNameParseError> {
        let value = value.into();
        if value.is_empty() {
            return Err(NodeGroupNameParseError::Empty);
        }
        if value.len() > NODE_GROUP_NAME_MAX_LEN {
            return Err(NodeGroupNameParseError::TooLong {
                max: NODE_GROUP_NAME_MAX_LEN,
                actual: value.len(),
            });
        }
        let is_label_alnum = |b: u8| b.is_ascii_lowercase() || b.is_ascii_digit();
        let bytes = value.as_bytes();
        if !bytes.iter().all(|&b| is_label_alnum(b) || b == b'-') {
            return Err(NodeGroupNameParseError::InvalidCharacter);
        }
        // Non-empty checked above, so first/last are always Some.
        let first = bytes.first().copied().unwrap_or_default();
        let last = bytes.last().copied().unwrap_or_default();
        if !is_label_alnum(first) || !is_label_alnum(last) {
            return Err(NodeGroupNameParseError::InvalidBoundary);
        }
        Ok(Self(value))
    }

    /// Returns the validated node group name.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for NodeGroupName {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.0.fmt(f)
    }
}

impl FromStr for NodeGroupName {
    type Err = NodeGroupNameParseError;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        Self::parse(value)
    }
}

impl TryFrom<String> for NodeGroupName {
    type Error = NodeGroupNameParseError;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        Self::parse(value)
    }
}

impl From<NodeGroupName> for String {
    fn from(value: NodeGroupName) -> Self {
        value.0
    }
}

/// Error returned when a node group template policy cannot be parsed.
///
/// # Examples
///
/// ```rust
/// # use std::str::FromStr;
/// # use pplx_space_common_core::types::NodeGroupTemplatePolicy;
/// assert!(NodeGroupTemplatePolicy::from_str("open").is_err());
/// ```
#[derive(Debug, Clone, Eq, PartialEq, thiserror::Error)]
#[error("unsupported node group template policy '{0}'")]
pub struct NodeGroupTemplatePolicyParseError(String);

/// Which templates an org-specific node group admits.
///
/// Only meaningful for org-specific groups; generic groups always use
/// [`NodeGroupTemplatePolicy::Default`] (enforced by a CHECK on the
/// `node_groups` table) because the compatibility predicate never consults the
/// allowlist for a generic group.
///
/// # Examples
///
/// ```rust
/// # use pplx_space_common_core::types::NodeGroupTemplatePolicy;
/// let policy: NodeGroupTemplatePolicy = "restricted".parse().unwrap();
/// assert_eq!(policy, NodeGroupTemplatePolicy::Restricted);
/// ```
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
#[cfg_attr(feature = "serde", serde(try_from = "String", into = "String"))]
#[derive(Clone, Copy, Debug, Eq, PartialEq, Ord, PartialOrd, Hash)]
pub enum NodeGroupTemplatePolicy {
    /// Admit all generic templates plus all of the owning org's own
    /// org-specific templates.
    Default,
    /// Admit exactly the templates in the group's allowlist (still subject to
    /// the hard cross-org rule).
    Restricted,
}

impl NodeGroupTemplatePolicy {
    /// Returns the canonical wire/database string for this policy.
    ///
    /// # Examples
    ///
    /// ```rust
    /// # use pplx_space_common_core::types::NodeGroupTemplatePolicy;
    /// assert_eq!(NodeGroupTemplatePolicy::Default.as_str(), "default");
    /// ```
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Default => "default",
            Self::Restricted => "restricted",
        }
    }
}

impl fmt::Display for NodeGroupTemplatePolicy {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

impl FromStr for NodeGroupTemplatePolicy {
    type Err = NodeGroupTemplatePolicyParseError;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        match value {
            "default" => Ok(Self::Default),
            "restricted" => Ok(Self::Restricted),
            other => Err(NodeGroupTemplatePolicyParseError(other.to_string())),
        }
    }
}

impl TryFrom<String> for NodeGroupTemplatePolicy {
    type Error = NodeGroupTemplatePolicyParseError;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        value.parse()
    }
}

impl From<NodeGroupTemplatePolicy> for String {
    fn from(value: NodeGroupTemplatePolicy) -> Self {
        value.as_str().to_string()
    }
}

/// The slice of a template row that authorization and placement consult.
///
/// The owning `org_id` and the launch-scope `visibility` are independent
/// axes: for a generic template the owner is don't-care, while an
/// org-specific template must have an owner (a database CHECK forbids the
/// unowned combination). If an unowned org-specific value is constructed
/// anyway, every predicate here fails closed: nobody may launch it and no
/// group admits it.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct TemplateCompatSpec {
    /// Immutable template name (the `templates` primary key).
    pub name: TemplateName,
    /// Owning org, if any.
    pub org_id: Option<OrgId>,
    /// Who may launch the template.
    pub visibility: TemplateVisibility,
}

impl TemplateCompatSpec {
    /// Returns whether `caller_org` may launch this template at all.
    ///
    /// This is the hard cross-org invariant: an org-specific template is
    /// launchable only by its owning org, and it can't be overridden by any
    /// node group configuration. The create-time authorization gate and the
    /// placement predicate both build on it. Delegates to
    /// [`TemplateVisibility::permits`] so this and the create-time gate share
    /// one definition of the rule (including failing closed on an unowned
    /// org-specific template).
    ///
    /// `caller_org` is `None` for a caller with **no org identity** — a
    /// warm-pool slot, built before anyone claims it. Such a caller may launch
    /// a generic template and no org-specific one: there is no org for
    /// `permits`'s ownership test to succeed against, which is the same answer
    /// the create gate gives an unowned org-specific template.
    ///
    /// # Examples
    ///
    /// ```rust
    /// # use pplx_space_accounts::OrgId;
    /// # use pplx_space_common_core::types::*;
    /// let org = OrgId::new();
    /// let template = TemplateCompatSpec {
    ///     name: TemplateName::parse("acme-tools").unwrap(),
    ///     org_id: Some(org),
    ///     visibility: TemplateVisibility::OrgSpecific,
    /// };
    /// assert!(template.launchable_by(Some(org)));
    /// assert!(!template.launchable_by(Some(OrgId::new())));
    /// assert!(!template.launchable_by(None));
    /// ```
    pub fn launchable_by(&self, caller_org: Option<OrgId>) -> bool {
        match caller_org {
            Some(caller_org) => self.visibility.permits(self.org_id, caller_org),
            // No org identity: generic templates only. Deliberately not
            // expressed through `permits`, which takes a concrete caller — an
            // org-less caller has nothing to compare against an owner, so the
            // answer comes from the visibility alone.
            None => self.visibility == TemplateVisibility::Generic,
        }
    }
}

/// Error returned when an allowlist entry violates a node group invariant.
#[derive(Debug, Clone, Eq, PartialEq, thiserror::Error)]
pub enum NodeGroupAllowlistError {
    #[error("org-specific template '{template}' cannot be allowlisted on a generic node group")]
    OrgSpecificOnGenericGroup { template: TemplateName },
    #[error(
        "template '{template}' is org-specific to org {template_org} and cannot be allowlisted \
         on a node group owned by org {group_org}"
    )]
    CrossOrgTemplate {
        template: TemplateName,
        template_org: OrgId,
        group_org: OrgId,
    },
    #[error("org-specific template '{template}' has no owning org and cannot be allowlisted")]
    UnownedOrgSpecificTemplate { template: TemplateName },
}

/// A node group's kind, carrying only the fields legal for that kind.
///
/// Encoding the generic-vs-dedicated split as a sum type makes the states the
/// `node_groups` CHECK constraints forbid unrepresentable in memory, so a
/// hand-built value can't reach [`NodeGroup::compatible`] in an inconsistent
/// shape:
///
/// - a generic group can't carry a `restricted` policy
///   (`node_groups_restricted_is_org_specific`) — `restricted` is only
///   meaningful alongside an owning org, and `compatible()` never consults the
///   allowlist for a generic group, so a restricted-generic value would
///   silently admit every generic template;
/// - a dedicated group can't be the default
///   (`node_groups_default_is_generic`) — `is_default` lives only on
///   [`NodeGroupPolicy::Generic`];
/// - a dedicated group always has an owning org.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum NodeGroupPolicy {
    /// Generic (shared) group: hosts any org's generic templates.
    Generic {
        /// Whether this is the singleton default generic group that ungrouped
        /// nodes resolve to.
        is_default: bool,
    },
    /// Hardware dedicated to `org_id`, admitting templates per
    /// `template_policy`.
    Dedicated {
        /// Owning org.
        org_id: OrgId,
        /// Which of the org's templates this group admits.
        template_policy: NodeGroupTemplatePolicy,
    },
}

/// A node group: a named pool of worker nodes.
///
/// Mirrors a `node_groups` row plus its `node_group_template_compat`
/// allowlist. The generic-vs-dedicated split and its per-kind fields live in
/// [`NodeGroupPolicy`], which keeps the DB CHECK invariants unrepresentable.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct NodeGroup {
    /// Stable identity (`node_groups.id`).
    pub id: NodeGroupId,
    /// Label-safe unique name (`node_groups.name`).
    pub name: NodeGroupName,
    /// Generic or dedicated, with the fields legal for that kind.
    pub policy: NodeGroupPolicy,
    /// Allowlist rows from `node_group_template_compat`; consulted only when
    /// the group is [`NodeGroupPolicy::Dedicated`] with
    /// [`NodeGroupTemplatePolicy::Restricted`].
    pub template_allowlist: BTreeSet<TemplateName>,
}

impl NodeGroup {
    /// Returns the owning org, or `None` for a generic (shared) group.
    pub fn org_id(&self) -> Option<OrgId> {
        match self.policy {
            NodeGroupPolicy::Generic { .. } => None,
            NodeGroupPolicy::Dedicated { org_id, .. } => Some(org_id),
        }
    }

    /// Returns whether this is the singleton default generic group. Dedicated
    /// groups are never default.
    pub fn is_default(&self) -> bool {
        matches!(self.policy, NodeGroupPolicy::Generic { is_default: true })
    }
    /// Returns whether a sandbox launched by `caller_org` from `template` may
    /// be placed in this node group.
    ///
    /// This is the single compatibility relation governing placement. Two
    /// isolation guarantees fall out of it:
    ///
    /// 1. **Data isolation** — an org-specific template only ever runs on its
    ///    owning org's dedicated nodes: generic groups admit only generic
    ///    templates, and the cross-org check rejects other orgs' groups.
    /// 2. **Capacity isolation** — a dedicated group only ever runs its owning
    ///    org's sandboxes, regardless of template visibility.
    ///
    /// On create, `caller_org` is the requesting org; on restore and
    /// drain-migrate paths it is the sandbox's owning org, not the triggering
    /// actor's. It is `None` for a pod with no org identity — a warm-pool slot
    /// — which admits generic templates on generic groups and nothing else.
    ///
    /// # Examples
    ///
    /// ```rust
    /// # use std::collections::BTreeSet;
    /// # use pplx_space_accounts::OrgId;
    /// # use pplx_space_common_core::types::*;
    /// let shared = NodeGroup {
    ///     id: NodeGroupId::new(),
    ///     name: NodeGroupName::parse("workers").unwrap(),
    ///     policy: NodeGroupPolicy::Generic { is_default: true },
    ///     template_allowlist: BTreeSet::new(),
    /// };
    /// let seed = TemplateCompatSpec {
    ///     name: TemplateName::parse("seed").unwrap(),
    ///     org_id: None,
    ///     visibility: TemplateVisibility::Generic,
    /// };
    /// assert!(shared.compatible(Some(OrgId::new()), &seed));
    /// assert!(shared.compatible(None, &seed));
    /// ```
    pub fn compatible(&self, caller_org: Option<OrgId>, template: &TemplateCompatSpec) -> bool {
        // Hard cross-org invariant — never overridable, not even by an
        // (invalid) allowlist row naming another org's template.
        if !template.launchable_by(caller_org) {
            return false;
        }
        match &self.policy {
            // Generic (shared) group: hosts only generic templates.
            NodeGroupPolicy::Generic { .. } => template.visibility == TemplateVisibility::Generic,
            // Dedicated group: serves only its owning org. An org-less caller
            // therefore matches no dedicated group at all — `Some(org) != None`
            // — which is what keeps a warm-pool slot off reserved hardware
            // without a sentinel org standing in for "nobody".
            NodeGroupPolicy::Dedicated {
                org_id,
                template_policy,
            } => {
                if caller_org != Some(*org_id) {
                    return false;
                }
                // Caller is the owning org; the template is generic or the
                // org's own org-specific (cross-org was rejected above).
                match template_policy {
                    NodeGroupTemplatePolicy::Default => true,
                    NodeGroupTemplatePolicy::Restricted => {
                        self.template_allowlist.contains(&template.name)
                    }
                }
            }
        }
    }

    /// Validates a candidate `node_group_template_compat` entry at write time.
    ///
    /// The allowlist widens nothing: it only narrows what a `restricted`
    /// group admits. Listing another org's org-specific template is rejected
    /// here so the hard cross-org rule can't even appear to be opted out of
    /// via allowlist rows. Generic templates may always be listed.
    pub fn validate_allowlist_entry(
        &self,
        template: &TemplateCompatSpec,
    ) -> Result<(), NodeGroupAllowlistError> {
        if template.visibility == TemplateVisibility::Generic {
            return Ok(());
        }
        let NodeGroupPolicy::Dedicated {
            org_id: group_org, ..
        } = self.policy
        else {
            return Err(NodeGroupAllowlistError::OrgSpecificOnGenericGroup {
                template: template.name.clone(),
            });
        };
        match template.org_id {
            None => Err(NodeGroupAllowlistError::UnownedOrgSpecificTemplate {
                template: template.name.clone(),
            }),
            Some(template_org) if template_org != group_org => {
                Err(NodeGroupAllowlistError::CrossOrgTemplate {
                    template: template.name.clone(),
                    template_org,
                    group_org,
                })
            }
            Some(_) => Ok(()),
        }
    }
}

