-- Deliberately no sandbox FK: deletion must not discard cloud cleanup authority.
CREATE TABLE sandbox_block_volumes (
    id UUID PRIMARY KEY,
    sandbox_id UUID NOT NULL UNIQUE,
    org_id UUID NOT NULL,
    managed_by TEXT NOT NULL,
    mount_spec JSONB NOT NULL,
    availability_zone TEXT NOT NULL,
    aws_volume_id TEXT UNIQUE,
    phase TEXT NOT NULL DEFAULT 'requested',
    delete_requested BOOLEAN NOT NULL DEFAULT FALSE,
    attachment_epoch BIGINT NOT NULL DEFAULT 0 CHECK (attachment_epoch >= 0),
    node_id UUID,
    instance_id TEXT,
    device_name TEXT,
    execution_id UUID,
    released_epoch BIGINT,
    filesystem_uuid UUID NOT NULL,
    initialization TEXT NOT NULL DEFAULT 'fresh',
    initialization_claim UUID,
    ever_exposed BOOLEAN NOT NULL DEFAULT FALSE,
    disk_generation BIGINT NOT NULL DEFAULT 0 CHECK (disk_generation >= 0),
    checkpoint_id UUID,
    checkpoint_generation BIGINT,
    activation_id UUID,
    activated_epoch BIGINT,
    last_error TEXT,
    revision BIGINT NOT NULL DEFAULT 0 CHECK (revision >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK ((node_id IS NULL) = (instance_id IS NULL)),
    CHECK ((node_id IS NULL) = (device_name IS NULL)),
    CHECK ((node_id IS NULL) = (execution_id IS NULL)),
    CHECK ((checkpoint_id IS NULL) = (checkpoint_generation IS NULL)),
    CHECK (checkpoint_generation IS NULL OR checkpoint_generation = disk_generation),
    CHECK (NOT ever_exposed OR initialization = 'ready'),
    CHECK (initialization != 'fresh' OR initialization_claim IS NULL),
    CHECK (initialization = 'fresh' OR initialization_claim IS NOT NULL),
    CHECK (released_epoch IS NULL OR released_epoch = attachment_epoch),
    UNIQUE (instance_id, device_name)
);

CREATE INDEX sandbox_block_volumes_reconcile
    ON sandbox_block_volumes (managed_by, phase, updated_at);
